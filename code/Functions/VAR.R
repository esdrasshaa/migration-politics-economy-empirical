VAR <- function(
    data,
    p,
    c = 1,
    trend = 0,
    x = NULL
){
  
  ## =========================================================
  ## Load SUR representation
  ## =========================================================
  
  source("Functions/SUR.R")
  
  ## =========================================================
  ## Build SUR representation
  ## =========================================================
  
  sur <- SUR(
    data = data,
    p = p,
    c = c,
    trend = trend,
    x = x
  )
  
  Y <- sur$Y
  X <- sur$X
  Y_initial <- sur$Y_initial
  
  ## =========================================================
  ## OLS estimate
  ##
  ## MATLAB "\" equivalent:
  ## beta = X \ Y
  ## =========================================================
  
  pi_hat <- qr.solve(
    X,
    Y
  )
  
  ## =========================================================
  ## Fitted values
  ## =========================================================
  
  Yfit <- X %*% pi_hat
  
  ## =========================================================
  ## Residuals
  ## =========================================================
  
  err <- Y - Yfit
  
  ## =========================================================
  ## Return
  ## =========================================================
  
  list(
    pi_hat = pi_hat,
    Y = Y,
    X = X,
    Y_initial = Y_initial,
    Yfit = Yfit,
    err = err
  )
}